import cors from 'cors';
import express from 'express';
import { PGlite } from '@electric-sql/pglite';
import { existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const projectRoot = path.resolve(__dirname, '..');

const PORT = Number(process.env.PORT || 3000);
const DB_PATH = process.env.PGLITE_DATA_DIR || path.join(projectRoot, '.pglite-data');
const MAX_MESSAGE_LENGTH = 1000;

const app = express();
const clients = new Set();
const db = new PGlite(DB_PATH);

app.use(cors());
app.use(express.json({ limit: '32kb' }));

async function initializeDatabase() {
  await db.exec(`
    CREATE TABLE IF NOT EXISTS messages (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      text TEXT NOT NULL CHECK (char_length(trim(text)) > 0),
      created_at TIMESTAMPTZ NOT NULL DEFAULT now()
    );

    CREATE INDEX IF NOT EXISTS messages_created_at_idx
      ON messages (created_at ASC, id ASC);
  `);
}

function normalizeMessage(row) {
  return {
    id: String(row.id),
    text: row.text,
    created_at:
      row.created_at instanceof Date ? row.created_at.toISOString() : row.created_at,
  };
}

async function getMessages() {
  const result = await db.query(`
    SELECT id::text AS id, text, created_at
    FROM messages
    ORDER BY created_at ASC, id ASC
  `);

  return result.rows.map(normalizeMessage);
}

async function createMessage(text) {
  const result = await db.query(
    `
      INSERT INTO messages (text)
      VALUES ($1)
      RETURNING id::text AS id, text, created_at
    `,
    [text],
  );

  return normalizeMessage(result.rows[0]);
}

function sendSse(res, payload) {
  res.write(`data: ${JSON.stringify(payload)}\n\n`);
}

function broadcastMessage(message) {
  for (const client of clients) {
    sendSse(client, message);
  }
}

app.get('/api/health', (_req, res) => {
  res.json({ ok: true });
});

app.get('/api/messages', async (_req, res, next) => {
  try {
    res.json(await getMessages());
  } catch (error) {
    next(error);
  }
});

app.post('/api/messages', async (req, res, next) => {
  try {
    const text = typeof req.body?.text === 'string' ? req.body.text.trim() : '';

    if (!text) {
      res.status(400).json({ error: 'Message text is required.' });
      return;
    }

    if (text.length > MAX_MESSAGE_LENGTH) {
      res.status(400).json({
        error: `Message text must be ${MAX_MESSAGE_LENGTH} characters or fewer.`,
      });
      return;
    }

    const message = await createMessage(text);
    broadcastMessage(message);
    res.status(201).json(message);
  } catch (error) {
    next(error);
  }
});

app.get('/api/stream', (req, res) => {
  res.setHeader('Content-Type', 'text/event-stream');
  res.setHeader('Cache-Control', 'no-cache, no-transform');
  res.setHeader('Connection', 'keep-alive');
  res.setHeader('X-Accel-Buffering', 'no');

  res.flushHeaders?.();
  res.write(': connected\n\n');

  clients.add(res);

  const heartbeat = setInterval(() => {
    res.write(': heartbeat\n\n');
  }, 25_000);

  req.on('close', () => {
    clearInterval(heartbeat);
    clients.delete(res);
    res.end();
  });
});

const distPath = path.join(projectRoot, 'dist');
if (existsSync(distPath)) {
  app.use(express.static(distPath));
  app.get('*', (_req, res) => {
    res.sendFile(path.join(distPath, 'index.html'));
  });
}

app.use((error, _req, res, _next) => {
  console.error(error);
  res.status(500).json({ error: 'Internal server error.' });
});

await initializeDatabase();

const server = app.listen(PORT, () => {
  console.log(`Message board server listening on http://localhost:${PORT}`);
  console.log(`PGLite data directory: ${DB_PATH}`);
});

function shutdown() {
  for (const client of clients) {
    client.end();
  }
  clients.clear();
  server.close(async () => {
    await db.close();
    process.exit(0);
  });
}

process.on('SIGINT', shutdown);
process.on('SIGTERM', shutdown);
