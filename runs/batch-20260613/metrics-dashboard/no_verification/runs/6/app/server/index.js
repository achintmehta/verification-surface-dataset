import express from 'express';
import cors from 'cors';
import { PGlite } from '@electric-sql/pglite';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(__dirname, '..');
const PORT = Number(process.env.PORT || 3000);

const db = new PGlite(`file://${path.join(rootDir, 'data', 'pglite')}`);

function seededRandom(seed) {
  let state = seed >>> 0;
  return () => {
    state = (state * 1664525 + 1013904223) >>> 0;
    return state / 0x100000000;
  };
}

function isoDate(daysAgo) {
  const fixedEnd = new Date('2025-05-30T12:00:00Z');
  fixedEnd.setUTCDate(fixedEnd.getUTCDate() - daysAgo);
  return fixedEnd.toISOString().slice(0, 10);
}

async function initializeDatabase() {
  await db.query(`
    CREATE TABLE IF NOT EXISTS daily_metrics (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      metric_date DATE UNIQUE NOT NULL,
      visitors INTEGER NOT NULL,
      revenue NUMERIC(12,2) NOT NULL
    );

    CREATE TABLE IF NOT EXISTS categories (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      label TEXT UNIQUE NOT NULL,
      value INTEGER NOT NULL
    );

    CREATE TABLE IF NOT EXISTS recent_items (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name TEXT NOT NULL,
      category TEXT NOT NULL,
      value INTEGER NOT NULL,
      created_at TIMESTAMP NOT NULL
    );

    CREATE TABLE IF NOT EXISTS settings (
      key TEXT PRIMARY KEY,
      value TEXT NOT NULL
    );
  `);

  const { rows } = await db.query('SELECT COUNT(*)::int AS count FROM daily_metrics');
  if (rows[0].count === 0) {
    await seedDatabase();
  }

  await db.query(
    `INSERT INTO settings (key, value) VALUES ('theme', 'light')
     ON CONFLICT (key) DO NOTHING`
  );
}

async function seedDatabase() {
  const rand = seededRandom(872341);
  const dailyRows = [];
  for (let i = 29; i >= 0; i -= 1) {
    const dayIndex = 29 - i;
    const weeklyWave = Math.sin(dayIndex / 4.2) * 280;
    const growth = dayIndex * 38;
    const visitors = Math.round(3550 + growth + weeklyWave + rand() * 520);
    const revenue = Number((42000 + visitors * (5.25 + rand() * 2.2) + dayIndex * 430).toFixed(2));
    dailyRows.push([isoDate(i), visitors, revenue]);
  }

  for (const [date, visitors, revenue] of dailyRows) {
    await db.query(
      'INSERT INTO daily_metrics (metric_date, visitors, revenue) VALUES ($1, $2, $3)',
      [date, visitors, revenue]
    );
  }

  const categories = [
    ['Enterprise Infrastructure & Compliance', 1285730],
    ['Product Analytics', 742320],
    ['Growth Campaigns', 486940],
    ['Customer Success', 358210],
    ['Platform Operations', 294875],
    ['Research Labs', 182460]
  ];
  for (const [label, value] of categories) {
    await db.query('INSERT INTO categories (label, value) VALUES ($1, $2)', [label, value]);
  }

  const itemNames = [
    'Quarterly executive review', 'Northwind renewal', 'Marketplace attribution audit',
    'Data warehouse optimization', 'Sales enablement push', 'Security posture report',
    'Mobile funnel analysis', 'Retention cohort deep dive', 'Onboarding experiment',
    'Cloud spend reconciliation', 'Partner channel forecast', 'Compliance evidence pack',
    'Enterprise migration plan', 'Pricing model refresh', 'Lifecycle campaign launch',
    'Support automation rollout', 'Regional demand snapshot', 'Trial activation review',
    'API performance review', 'Revenue operations sync'
  ];

  for (let i = 0; i < 20; i += 1) {
    const category = categories[i % categories.length][0];
    const value = Math.round(18500 + rand() * 164000 + i * 1700);
    const created = new Date('2025-05-30T18:00:00Z');
    created.setUTCDate(created.getUTCDate() - i);
    created.setUTCHours(9 + (i % 8), 15 + (i * 7) % 40, 0, 0);
    await db.query(
      'INSERT INTO recent_items (name, category, value, created_at) VALUES ($1, $2, $3, $4)',
      [itemNames[i], category, value, created.toISOString()]
    );
  }
}

function parseNumber(value) {
  return Number(value ?? 0);
}

const app = express();
app.use(cors());
app.use(express.json());

app.get('/api/health', (_req, res) => res.json({ ok: true }));

app.get('/api/summary', async (_req, res, next) => {
  try {
    const totals = await db.query(`
      SELECT
        COALESCE(SUM(visitors), 0)::int AS total_visitors,
        COALESCE(SUM(revenue), 0)::numeric(12,2) AS total_revenue
      FROM daily_metrics
    `);
    const bestDay = await db.query(`
      SELECT metric_date::text AS date, visitors, revenue::numeric(12,2) AS revenue
      FROM daily_metrics
      ORDER BY revenue DESC, visitors DESC
      LIMIT 1
    `);
    const trendRows = await db.query(`
      SELECT visitors
      FROM daily_metrics
      ORDER BY metric_date DESC
      LIMIT 14
    `);
    const visitors = trendRows.rows.map((row) => Number(row.visitors));
    const recent7 = visitors.slice(0, 7).reduce((sum, value) => sum + value, 0);
    const previous7 = visitors.slice(7, 14).reduce((sum, value) => sum + value, 0);
    const trendPercent = previous7 === 0 ? 0 : ((recent7 - previous7) / previous7) * 100;

    res.json({
      totalVisitors: Number(totals.rows[0].total_visitors),
      totalRevenue: parseNumber(totals.rows[0].total_revenue),
      bestDay: {
        date: bestDay.rows[0]?.date,
        visitors: Number(bestDay.rows[0]?.visitors || 0),
        revenue: parseNumber(bestDay.rows[0]?.revenue)
      },
      sevenDayTrendPercent: Number(trendPercent.toFixed(1))
    });
  } catch (error) {
    next(error);
  }
});

app.get('/api/timeseries', async (_req, res, next) => {
  try {
    const { rows } = await db.query(`
      SELECT metric_date::text AS date, visitors, revenue::numeric(12,2) AS revenue
      FROM daily_metrics
      ORDER BY metric_date ASC
    `);
    res.json(rows.map((row) => ({
      date: row.date,
      visitors: Number(row.visitors),
      revenue: parseNumber(row.revenue)
    })));
  } catch (error) {
    next(error);
  }
});

app.get('/api/categories', async (_req, res, next) => {
  try {
    const { rows } = await db.query('SELECT label, value FROM categories ORDER BY value DESC');
    res.json(rows.map((row) => ({ label: row.label, value: Number(row.value) })));
  } catch (error) {
    next(error);
  }
});

app.get('/api/recent', async (_req, res, next) => {
  try {
    const { rows } = await db.query(`
      SELECT id, name, category, value, created_at::text AS created_at
      FROM recent_items
      ORDER BY created_at DESC
      LIMIT 20
    `);
    res.json(rows.map((row) => ({
      id: Number(row.id),
      name: row.name,
      category: row.category,
      value: Number(row.value),
      createdAt: row.created_at
    })));
  } catch (error) {
    next(error);
  }
});

app.get('/api/settings', async (_req, res, next) => {
  try {
    const { rows } = await db.query("SELECT value FROM settings WHERE key = 'theme'");
    const theme = rows[0]?.value === 'dark' ? 'dark' : 'light';
    res.json({ theme });
  } catch (error) {
    next(error);
  }
});

app.put('/api/settings', async (req, res, next) => {
  try {
    const theme = req.body?.theme;
    if (!['light', 'dark'].includes(theme)) {
      return res.status(400).json({ error: 'theme must be "light" or "dark"' });
    }
    await db.query(
      `INSERT INTO settings (key, value) VALUES ('theme', $1)
       ON CONFLICT (key) DO UPDATE SET value = EXCLUDED.value`,
      [theme]
    );
    res.json({ theme });
  } catch (error) {
    next(error);
  }
});

app.use((error, _req, res, _next) => {
  console.error(error);
  res.status(500).json({ error: 'Internal server error' });
});

initializeDatabase()
  .then(() => {
    app.listen(PORT, () => {
      console.log(`Metrics API listening on http://localhost:${PORT}`);
    });
  })
  .catch((error) => {
    console.error('Failed to initialize database', error);
    process.exit(1);
  });
