import express from 'express';
import cors from 'cors';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { PGlite } from '@electric-sql/pglite';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '..');
const PORT = process.env.PORT || 3000;

const app = express();
app.use(cors());
app.use(express.json());

const db = new PGlite(path.join(rootDir, 'pglite-data'));

function seededDailyRows() {
  const rows = [];
  const start = new Date(Date.UTC(2025, 0, 1));
  for (let i = 0; i < 30; i += 1) {
    const day = new Date(start);
    day.setUTCDate(start.getUTCDate() + i);
    const date = day.toISOString().slice(0, 10);
    const visitors = 18250 + i * 615 + ((i * 37) % 11) * 220 + (i % 6 === 0 ? 1900 : 0) - (i % 10 === 3 ? 1100 : 0);
    const revenue = Number((visitors * (2.45 + (i % 5) * 0.18) + 8500 + (i % 4) * 1350).toFixed(2));
    rows.push({ date, visitors, revenue });
  }
  return rows;
}

const categoryRows = [
  ['Organic Search', 684320],
  ['Paid Acquisition', 472180],
  ['Enterprise Infrastructure & Compliance', 1250000],
  ['Partner Marketplace', 318940],
  ['Customer Success', 219780],
  ['Product-Led Growth', 536450]
];

const itemCategories = categoryRows.map(([label]) => label);
function seededRecentRows() {
  const base = new Date(Date.UTC(2025, 0, 30, 14, 30, 0));
  return Array.from({ length: 20 }, (_, i) => {
    const created = new Date(base);
    created.setUTCHours(base.getUTCHours() - i * 11);
    const value = 18800 + ((i * 7919) % 83500) + (i === 4 ? 1000000 : 0);
    return {
      name: `Account ${String.fromCharCode(65 + (i % 26))}-${2025 + i}`,
      category: itemCategories[(i * 2 + 1) % itemCategories.length],
      value,
      created_at: created.toISOString()
    };
  });
}

async function query(sql, params = []) {
  return db.query(sql, params);
}

async function initDb() {
  await db.exec(`
    CREATE TABLE IF NOT EXISTS daily_metrics (
      date date PRIMARY KEY,
      visitors integer NOT NULL,
      revenue numeric(12,2) NOT NULL
    );

    CREATE TABLE IF NOT EXISTS categories (
      id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      label text NOT NULL,
      value integer NOT NULL
    );

    CREATE TABLE IF NOT EXISTS recent_items (
      id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name text NOT NULL,
      category text NOT NULL,
      value integer NOT NULL,
      created_at timestamptz NOT NULL
    );

    CREATE TABLE IF NOT EXISTS settings (
      key text PRIMARY KEY,
      value text NOT NULL
    );
  `);

  const dailyCount = await query('SELECT COUNT(*)::int AS count FROM daily_metrics');
  if (dailyCount.rows[0].count === 0) {
    for (const row of seededDailyRows()) {
      await query('INSERT INTO daily_metrics (date, visitors, revenue) VALUES ($1, $2, $3)', [row.date, row.visitors, row.revenue]);
    }
  }

  const categoryCount = await query('SELECT COUNT(*)::int AS count FROM categories');
  if (categoryCount.rows[0].count === 0) {
    for (const [label, value] of categoryRows) {
      await query('INSERT INTO categories (label, value) VALUES ($1, $2)', [label, value]);
    }
  }

  const recentCount = await query('SELECT COUNT(*)::int AS count FROM recent_items');
  if (recentCount.rows[0].count === 0) {
    for (const item of seededRecentRows()) {
      await query('INSERT INTO recent_items (name, category, value, created_at) VALUES ($1, $2, $3, $4)', [item.name, item.category, item.value, item.created_at]);
    }
  }

  await query("INSERT INTO settings (key, value) VALUES ('theme', 'light') ON CONFLICT (key) DO NOTHING");
}

function toIsoDate(value) {
  if (value instanceof Date) return value.toISOString().slice(0, 10);
  return String(value).slice(0, 10);
}

function mapSeries(rows) {
  return rows.map((r) => ({
    date: toIsoDate(r.date),
    visitors: Number(r.visitors),
    revenue: Number(r.revenue)
  }));
}

app.get('/api/summary', async (_req, res, next) => {
  try {
    const { rows } = await query('SELECT date, visitors, revenue FROM daily_metrics ORDER BY date ASC');
    const series = mapSeries(rows);
    const totalVisitors = series.reduce((sum, r) => sum + r.visitors, 0);
    const totalRevenue = Number(series.reduce((sum, r) => sum + r.revenue, 0).toFixed(2));
    const best = series.reduce((max, r) => (r.visitors > max.visitors ? r : max), series[0]);
    const last7 = series.slice(-7).reduce((sum, r) => sum + r.visitors, 0);
    const prev7 = series.slice(-14, -7).reduce((sum, r) => sum + r.visitors, 0);
    const trendPct = prev7 === 0 ? 0 : Number((((last7 - prev7) / prev7) * 100).toFixed(1));
    res.json({
      totalVisitors,
      totalRevenue,
      bestDay: { date: best.date, visitors: best.visitors, revenue: best.revenue },
      trendPct
    });
  } catch (err) {
    next(err);
  }
});

app.get('/api/timeseries', async (_req, res, next) => {
  try {
    const { rows } = await query('SELECT date, visitors, revenue FROM daily_metrics ORDER BY date ASC');
    res.json(mapSeries(rows));
  } catch (err) {
    next(err);
  }
});

app.get('/api/categories', async (_req, res, next) => {
  try {
    const { rows } = await query('SELECT label, value FROM categories ORDER BY value DESC');
    res.json(rows.map((r) => ({ label: r.label, value: Number(r.value) })));
  } catch (err) {
    next(err);
  }
});

app.get('/api/recent', async (_req, res, next) => {
  try {
    const { rows } = await query('SELECT name, category, value, created_at FROM recent_items ORDER BY created_at DESC LIMIT 20');
    res.json(rows.map((r) => ({ name: r.name, category: r.category, value: Number(r.value), created_at: new Date(r.created_at).toISOString() })));
  } catch (err) {
    next(err);
  }
});

app.get('/api/settings', async (_req, res, next) => {
  try {
    const { rows } = await query("SELECT value FROM settings WHERE key = 'theme'");
    const theme = rows[0]?.value === 'dark' ? 'dark' : 'light';
    res.json({ theme });
  } catch (err) {
    next(err);
  }
});

app.put('/api/settings', async (req, res, next) => {
  try {
    const { theme } = req.body ?? {};
    if (!['light', 'dark'].includes(theme)) {
      return res.status(400).json({ error: 'theme must be "light" or "dark"' });
    }
    await query("INSERT INTO settings (key, value) VALUES ('theme', $1) ON CONFLICT (key) DO UPDATE SET value = EXCLUDED.value", [theme]);
    res.json({ theme });
  } catch (err) {
    next(err);
  }
});

app.get('/api/health', (_req, res) => res.json({ ok: true }));

const distDir = path.join(rootDir, 'dist');
if (process.env.NODE_ENV === 'production') {
  app.use(express.static(distDir));
  app.get(/.*/, (_req, res) => res.sendFile(path.join(distDir, 'index.html')));
}

app.use((err, _req, res, _next) => {
  console.error(err);
  res.status(500).json({ error: 'Internal server error' });
});

initDb().then(() => {
  app.listen(PORT, () => console.log(`Metrics API listening on http://localhost:${PORT}`));
}).catch((err) => {
  console.error('Failed to initialize database', err);
  process.exit(1);
});
